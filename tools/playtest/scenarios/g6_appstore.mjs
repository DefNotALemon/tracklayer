// App Store upgrade: recommended-order strip, owned state, GET flow, re-sort after purchase, stills (desktop + phone portrait).
import { boot, ev, shot, send, sleep, done } from "../lib.mjs";
let fails = 0; const ok = (c, m) => { console.log((c ? "ok   " : "FAIL ") + m); if (!c) fails++; };
const J = async e => JSON.parse(await ev(`JSON.stringify(${e})`));
const view = async (w, h, mobile) => { await send("Emulation.setDeviceMetricsOverride", { width: w, height: h, deviceScaleFactor: mobile ? 2 : 1, mobile }); await ev(`dispatchEvent(new Event("resize")); true`); await sleep(800); };
const strip = () => J(`[...document.querySelectorAll("#tabV .tsstep")].map(e => ({ id: e.dataset.sid, step: +e.dataset.step, got: e.classList.contains("got"), next: e.classList.contains("next") }))`);
const rows = () => J(`[...document.querySelectorAll("#tabV .tsto")].map(e => e.dataset.sid)`);
const overflow = () => J(`(() => { const s = document.querySelector("#tabV .tssteps"), r = s.getBoundingClientRect(); return { sw: s.scrollWidth, cw: s.clientWidth, ok: [...s.children].every(c => c.getBoundingClientRect().right <= r.right + 1 && c.getBoundingClientRect().left >= r.left - 1) }; })()`);
await boot();
await ev("tutSkip(); GS.cash = 500; delete GS.apps.freight; delete GS.apps.rescue; delete GS.apps.realestate; TABLET.toggle(true, 'store'); true"); await sleep(1200);
let s = await strip();
ok(s.length === 4 && s.map(x => x.step).join() === "1,2,3,4", "strip has 4 steps in rec order 1-4");
ok(s.map(x => x.id).join() === "crew,freight,realestate,rescue", "order = crew, freight, realestate, rescue (" + s.map(x => x.id) + ")");
ok(s[0].got && !s[0].next, "Trail Crew shows as owned (GOT IT), not next");
ok(s[1].next && s.filter(x => x.next).length === 1, "Freight is the single highlighted next step");
ok((await rows()).join() === "crew,freight,realestate,rescue", "list sorted by rec");
ok(await J(`document.querySelector('#tabV [data-sid=crew] [data-get]').textContent === "OPEN"`), "Trail Crew row says OPEN");
await shot("g6_store_desktop");
const o = await overflow(); ok(o.ok, "desktop strip does not overflow");
const c0 = await J("GS.cash");
await ev(`document.querySelector('#tabV [data-get=freight]').click(); true`); await sleep(500);
const a = await J("({ cash: GS.cash, f: GS.apps.freight })");
ok(a.f === 1 && a.cash === c0 - 120, `buying Freight deducts $120 and sets GS.apps.freight (${c0} -> ${a.cash})`);
s = await strip();
ok(s[1].got && s[2].next && s.filter(x => x.next).length === 1, "after purchase Freight is GOT IT and Real Estate is next");
ok(await J(`document.querySelector('#tabV [data-sid=freight] [data-get]').textContent === "OPEN"`), "Freight row flipped to OPEN");
// poor: GET blocked
await ev("GS.cash = 10; TABLET.render(); true"); await sleep(300);
await ev(`document.querySelector('#tabV [data-get=rescue]').click(); true`); await sleep(300);
ok(await J("!GS.apps.rescue && GS.cash === 10"), "too poor: Rescue not bought, cash untouched");
await ev("GS.cash = 500; TABLET.render(); true"); await sleep(300);
await shot("g6_store_afterbuy");
// phone portrait
await view(390, 844, true);
await ev(`SET.touch='on'; setTouchUI(); TABLET.toggle(true, 'store'); TABLET.render(); true`); await sleep(900);
const po = await overflow(); ok(po.ok && po.sw <= po.cw + 1, "phone portrait strip fits (" + JSON.stringify(po) + ")");
const page = await J(`(() => { const v = document.querySelector("#tabV"); return v.scrollWidth <= v.clientWidth + 1; })()`);
ok(page, "phone portrait: no horizontal scroll in the app");
await shot("g6_store_phone");
await view(1280, 720, false);
await ev("TABLET.toggle(true,'store'); true");
await done(fails ? 1 : 0);
