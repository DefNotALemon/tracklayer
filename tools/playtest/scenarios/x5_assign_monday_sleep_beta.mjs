// Beta 5.4a2: truck-assigned plow driver x a real Monday (not stubbed), a sleep through a storm, wage unpaid, reload mid-out.
import { boot, ev, sleep, done, reload } from "../lib.mjs";
let fails = 0; const ok = (c, m) => { console.log((c ? "ok   " : "FAIL ") + m); if (!c) fails++; };
const J = async e => JSON.parse(await ev(`JSON.stringify(${e})`));
const section = async (n, f) => { console.log("--- " + n); try { await f(); } catch (e) { ok(false, n + " threw: " + String(e.message).slice(0, 300)); } };
// 5.4b2b: PDR.wayMax = 0 here: the truck is on the road at once, as when this was written (its drive from the spot has its own test, x5_plowdriver_way.mjs)
const SETUP = `TLXPL.PDR.wayMax = 0; tutSkip(); crashCancel(); FOOT.on = false; WX.at = () => 0; GS.storm = 0; window.__mon = TLX.monday; TLX.setOn("police", false); TLX.setOn("traffic", false); if (window.TLXT) { TLXT.hold = true; for (const c of TLXT.cars) c.on = false; } true`;
const KIT = `(() => {
  window.__rt = id => TLXR.routes.find(r => r.id === id);
  window.__q = (h, st) => { st = st || 0.5; for (let t = 0; t < h - 1e-6; t += st) { GS.hour += Math.min(st, h - t); TLX.state("roads").h = GS.hour; TLXPL.con.step(); } return true; };
  window.__pdr = id => { const q = TLX.state("plow").pdr[id]; return q ? JSON.parse(JSON.stringify(q)) : null; };
  window.__drv = (id, work, xp, hap) => { const m = TLX.staff.at("plow:" + id); m.tr.work = work; m.tr.temper = 0; m.xpReal = xp; m.hap = hap; m.mood = 0; m.wage = TLX.staff.fair(m); return TLXPL.pdr.skill(m, id); };
  window.__tk = uid => { const r = TLXV.state().owned.find(q => q.uid === uid); return r ? { out: r.out || null, fuel: +r.fuel.toFixed(2), x: r.x, z: r.z, cond: +TLXPL.condOf(uid).toFixed(2) } : null; };
  return true; })()`;
await boot(); await ev(SETUP); await sleep(600); await ev(KIT);
await ev(`GS.hour = 34; TLX.state("roads").h = 34; GS.cash = 90000; true`);
const pick = await J(`TLXPL.con.routes().map(r => { let b = -1; for (let i = 4; i < r.seg.length - 1; i++) if (r.seg[i].legs.length && r.seg[i - 1].legs.length && r.seg[i + 1].legs.length && (i + 1) * 400 + 40 <= r.len) { b = i; if (i >= 5) break; } return { id: r.id, i: b }; }).filter(q => q.i >= 4)`);
const R0 = pick.find(q => q.id === "dyfjord") || pick[0];
const rid = JSON.stringify(R0.id), I = R0.i;
await ev(`GS.lic = GS.lic || {}; GS.lic.freight = true; TLXV.buy("plowtruck"); true`); await sleep(700);
const UID = await ev(`TLXV.state().owned.find(r => r.id === "plowtruck").uid`), uid = JSON.stringify(UID);
await ev(`TLXPL.PDR.mine = 1; TLXPL.con.sign(${rid}); TLX.staff.tick(); true`); await sleep(300);
const DID = (await J(`TLX.state("staff").apps`))[0].id;
await ev(`TLX.staff.hire(${DID}); __drv(${rid}, 1, 10, 70); TLX.staff.xact(${DID}, "a" + ${uid}); true`);
const snow = (i, v) => ev(`TLXR.setSnow(${rid}, ${v}, ${i}); TLXPL.con.step(); true`);
await section("A real Monday while the truck is out", async () => {
  await snow(I - 1, 0.5); await snow(I, 0.6);
  await ev(`__q(0.9, 0.3); __q(0.05, 0.05); true`);
  let a = await J(`({ q: __pdr(${rid}), t: __tk(${uid}) })`);
  ok(a.q.st === "out" && a.t.out, "driver out in the assigned truck: " + JSON.stringify(a.q).slice(0, 160));
  const w0 = await J(`({ cash: GS.cash, owed: TLX.state("staff").owed })`);
  const r = await ev(`(() => { try { __mon({ label: "Mon 4 Jan" }); return "ok"; } catch (e) { return "THREW " + e.message; } })()`);
  ok(r === "ok", "TLX.monday with a truck out does not throw: " + r);
  const b = await J(`({ q: __pdr(${rid}), t: __tk(${uid}), cash: GS.cash, owed: TLX.state("staff").owed })`);
  console.log("  after Monday", JSON.stringify(b), "cash", b.cash - w0.cash);
  ok(b.cash < w0.cash || b.owed > 0, "the wage was paid or owed");
  ok(b.t && (b.t.out || b.q.st !== "out"), "truck record still consistent (out only while driver out)");
  await ev(`__q(2, 0.25); true`);
  const c = await J(`({ q: __pdr(${rid}), t: __tk(${uid}), s: __rt(${rid}).st.s[${I}] })`);
  ok(c.q.st === "home" && !c.t.out && c.s === 0, "back home, truck back in its spot, stretch open: " + JSON.stringify(c));
});
await section("B sleep through a storm with the truck assigned", async () => {
  const f0 = (await J(`__tk(${uid})`)), e0 = f0.cond;
  await snow(I - 1, 0.5); await snow(I, 0.6);
  const c0 = await ev("GS.cash");
  const r = await ev(`(() => { try { GS.hour += 9; TLX.state("roads").h = GS.hour; TLXPL.con.step(); return "ok"; } catch (e) { return "THREW " + e.message; } })()`);
  ok(r === "ok", "9 h sleep no throw");
  const a = await J(`({ q: __pdr(${rid}), t: __tk(${uid}), cash: GS.cash, s: __rt(${rid}).st.s[${I}] })`);
  console.log("  ", JSON.stringify(a), "fuel", f0.fuel, "->", a.t.fuel, "edge", e0, "->", a.t.cond);
  ok(a.q.st === "home" && !a.t.out && Number.isFinite(a.cash), "slept: driver home, truck back");
  ok(a.t.fuel <= f0.fuel && a.t.cond <= e0, "the sleep burned the owner's diesel / edge, never added");
  const log = await J(`TABLET.log.map(n => n.title + " | " + n.body).slice(-3)`);
  console.log("  notes", JSON.stringify(log));
});
await section("C wage unpaid, then reload mid-out", async () => {
  await ev(`GS.cash = 0; __mon({ label: "Mon 11 Jan" }); true`);
  await snow(I - 1, 0.5); await snow(I, 0.6); await ev(`__q(1, 0.25); true`);
  let a = await J(`({ q: __pdr(${rid}), t: __tk(${uid}), owed: TLX.state("staff").owed })`);
  ok(a.owed > 0 && a.q.st === "home" && !a.t.out, "owed: truck stays in its spot, driver does not go: " + JSON.stringify(a.q).slice(0, 120));
  await ev(`GS.cash = 9000; TLX.staff.payOwed(); __q(0.9, 0.3); __q(0.05, 0.05); true`);
  a = await J(`({ q: __pdr(${rid}), t: __tk(${uid}) })`);
  ok(a.q.st === "out" && a.t.out, "paid: out again");
  await reload(); await ev(SETUP); await sleep(500); await ev(KIT);
  const b = await J(`({ q: __pdr(${rid}), t: __tk(${uid}) })`);
  ok(b.t && b.t.out && b.q && b.q.truck === UID, "reload mid-out keeps truck out and assigned: " + JSON.stringify(b).slice(0, 160));
  await ev(`__q(3, 0.25); true`);
  const c = await J(`({ q: __pdr(${rid}), t: __tk(${uid}) })`);
  ok(c.q.st === "home" && !c.t.out, "after reload the driver still finishes and brings the truck home: " + JSON.stringify(c).slice(0, 160));
  const txt = await ev(`TABLET.toggle(true, "staff"); TABLET.render(); true`); await sleep(450);
  ok(!/undefined|NaN/.test(await ev(`$("tabS").textContent`)), "Staff card clean");
});
console.log(fails ? `x5_assign_monday_sleep_beta: ${fails} FAILED` : "x5_assign_monday_sleep_beta: all ok");
await done(fails ? 1 : 0);
